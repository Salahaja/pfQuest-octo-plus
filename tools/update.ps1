<#
.SYNOPSIS
  Brings pfQuest-octo-plus up to date with the server in one go.

.DESCRIPTION
  1. pulls the three source databases (TKB, ryanmr82, pfQuest-octo)
  2. asks octowow.st/db what changed
       -Mode Quick  (default) new quests only: the categories that hold quests,
                    the custom list, and the ids just past each cluster's last
                    quest. About 10-15 minutes.
       -Mode Full   every page older than a week, every category, every id
                    sweep. Hours; it resumes where it stopped if the site's
                    DDoS filter cuts it off.
  3. builds, reads anything the build references that the server was never
     asked about, and builds again
  4. tests the result the way the client loads it, and compares it with the
     server (check.py --strict). Anything off stops here, nothing committed.
  5. if the database really changed (not just the build stamp): bumps the
     patch version, commits, pushes to GitHub, and fast-forwards the installed
     copy in AddOns so OctoLauncher sees it as up to date.

  Every run writes a log to <work>\update-logs.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\update.ps1
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\update.ps1 -Mode Full
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\update.ps1 -NoPush
#>
param(
    [ValidateSet('Quick', 'Full')] [string] $Mode = 'Quick',
    # commit locally only; the installed copy is then pulled from this repo
    [switch] $NoPush,
    # build and check, but leave git alone
    [switch] $DryRun,
    [string] $Work = (Split-Path (Split-Path $PSScriptRoot)),
    [string] $AddOns = 'D:\stuff\client - Copy (2)\Interface\AddOns'
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot
$tools = $PSScriptRoot
$data = Join-Path $Work 'octodb-data'
$cache = Join-Path $Work 'build-cache'
$pfquest = Join-Path $AddOns 'pfQuest'
$installed = Join-Path $AddOns 'pfQuest-octo-plus'
# lines that change on every build: the stamps, not the data
$stamp = @('-I', 'GENERATED by tools/build.py on', '-I', 'from the server inventory exported')
$generated = @('db', 'init', 'patchtable.lua', 'BUILD.md', 'pfQuest-octo-plus.toc')

$logs = Join-Path $Work 'update-logs'
New-Item -ItemType Directory -Force $logs | Out-Null
$log = Join-Path $logs ('update-{0:yyyyMMdd-HHmm}-{1}.log' -f (Get-Date), $Mode.ToLower())
Start-Transcript -Path $log | Out-Null

# one run at a time: a scheduled run and a manual one would share the sqlite file
$lock = Join-Path $Work 'update.lock'
try {
    $lockFile = [System.IO.File]::Open($lock, 'OpenOrCreate', 'ReadWrite', 'None')
} catch {
    Write-Host 'Another update is running (update.lock is held). Stopping.' -ForegroundColor Yellow
    try { Stop-Transcript | Out-Null } catch { }
    exit 3
}

function Step($text) { Write-Host "`n== $text" -ForegroundColor Cyan }
# the finally block at the bottom releases the lock and closes the log
function Fail($text, $code = 1) {
    Write-Host "`nFAILED: $text" -ForegroundColor Red
    exit $code
}
# native commands: stream their output, stop on a non-zero exit. Piping through
# Out-Host is what puts a program's output in the 5.1 transcript.
function Run($what, [scriptblock] $cmd) {
    & $cmd | Out-Host
    if ($LASTEXITCODE -ne 0) { Fail "$what (exit $LASTEXITCODE)" $LASTEXITCODE }
}
function Octodb([string[]] $more) {
    & python -u (Join-Path $tools 'octodb.py') @more --data $data | Out-Host
    if ($LASTEXITCODE -eq 2) {
        Fail ("the site stopped answering (DDoS filter or outage). Everything fetched is kept; " +
              "run this again later and it carries on.") 2
    }
    if ($LASTEXITCODE -ne 0) { Fail "octodb.py $($more[0]) (exit $LASTEXITCODE)" }
}
function RepoGit { & git -C $repo @args }
# quest id -> name, from the inventory (too big for ConvertFrom-Json in 5.1)
function Names([string[]] $ids) {
    if (-not $ids) { return }
    & python -I -c "import json,sys; d=json.load(open(sys.argv[1],encoding='utf-8'))['quests']; [print(q, (d.get(q) or {}).get('name') or '') for q in sys.argv[2:]]" (Join-Path $data 'octodb.json') @ids
}
$env:PYTHONIOENCODING = 'utf-8'

# test_build.lua reads the .toc from the current folder
Push-Location $repo
try {
    Write-Host "pfQuest-octo-plus update, $Mode mode, $(Get-Date -Format 'yyyy-MM-dd HH:mm')"
    if ((RepoGit status --porcelain -- tools) -and -not $DryRun) {
        Fail 'tools/ has uncommitted changes. Commit or stash them first, so an automatic commit does not sweep them up.'
    }

    Step 'Source databases'
    foreach ($src in 'tkb-turtle', 'ryanmr82-turtle', 'paokkerkir-octo') {
        $dir = Join-Path $Work $src
        $before = & git -C $dir rev-parse --short HEAD
        & git -C $dir pull -q --ff-only
        if ($LASTEXITCODE -ne 0) {
            Write-Host "  $src : pull failed, building from $before" -ForegroundColor Yellow
        } else {
            $after = & git -C $dir rev-parse --short HEAD
            Write-Host ("  {0,-16} {1}" -f $src, $(if ($before -eq $after) { "$after (unchanged)" } else { "$before -> $after" }))
        }
    }

    Step 'Server inventory'
    $seed = @('--pfquest', $pfquest)
    foreach ($src in 'tkb-turtle', 'ryanmr82-turtle', 'paokkerkir-octo') { $seed += @('--pfquest', (Join-Path $Work $src)) }
    $known = @()
    foreach ($f in Get-ChildItem (Join-Path $Work 'out\*') -Include '*.tsv', 'site.txt' -ErrorAction SilentlyContinue) {
        $known += @('--known', $f.FullName)
    }
    if ($Mode -eq 'Full') {
        Octodb (@('run', '--refresh-days', '7') + $seed + $known)
    } else {
        Octodb (@('discover', '--populated-only', '--refresh-days', '0.8') + $seed)
        Octodb (@('sweep', '--refresh-days', '0.8') + $known)
        # pages never read yet only: what the two steps above just found
        Octodb @('quests', '--refresh-days', '3650')
        Octodb @('refs', '--refresh-days', '3650')
    }

    $quests = Join-Path $cache 'expected-quests.txt'
    $was = if (Test-Path $quests) { Get-Content $quests } else { @() }

    Step 'Build'
    Run 'build.py' { python -u (Join-Path $tools 'build.py') --octodb $data --work $Work --pfquest $pfquest }
    $unverified = Join-Path $cache 'unverified.txt'
    if ((Test-Path $unverified) -and (Get-Item $unverified).Length -gt 0) {
        Step 'Ids the build references that the server was never asked about'
        Octodb @('refs', '--refresh-days', '3650', '--extra', $unverified)
        Run 'build.py (second pass)' { python -u (Join-Path $tools 'build.py') --octodb $data --work $Work --pfquest $pfquest }
    }

    Step 'Test'
    Run 'test_build.lua' { lua (Join-Path $tools 'test_build.lua') $pfquest $cache }
    Run 'test_window.lua' { lua (Join-Path $tools 'test_window.lua') $pfquest $cache }
    Run 'check.py --strict' { python -u (Join-Path $tools 'check.py') --strict --octodb $data --pfquest $pfquest $repo }

    $now = Get-Content $quests
    $added = @($now | Where-Object { $was -notcontains $_ })
    $gone = @($was | Where-Object { $now -notcontains $_ })

    Step 'Result'
    & git -C $repo diff --quiet @stamp -- @generated
    if ($LASTEXITCODE -eq 0) {
        Write-Host 'No change to the database. Nothing to commit.' -ForegroundColor Green
        RepoGit checkout -q -- @generated
        return
    }
    Write-Host ("Quests added: {0}   removed: {1}" -f $added.Count, $gone.Count)
    $addedNames = @(Names ($added | Select-Object -First 40))
    $addedNames | ForEach-Object { Write-Host "  + $_" }
    $gone | Select-Object -First 40 | ForEach-Object { Write-Host "  - $_" }
    RepoGit diff --stat @stamp -- @generated

    if ($DryRun) {
        Write-Host "`n-DryRun: left uncommitted in $repo" -ForegroundColor Yellow
        return
    }

    Step 'Release'
    $build = Join-Path $tools 'build.py'
    $text = [System.IO.File]::ReadAllText($build)
    $m = [regex]::Match($text, 'VERSION = "(\d+)\.(\d+)\.(\d+)"')
    $version = '{0}.{1}.{2}' -f $m.Groups[1].Value, $m.Groups[2].Value, ([int]$m.Groups[3].Value + 1)
    $text = $text.Substring(0, $m.Index) + "VERSION = `"$version`"" + $text.Substring($m.Index + $m.Length)
    [System.IO.File]::WriteAllText($build, $text)
    # once more, so the .toc and BUILD.md carry the new version
    Run 'build.py (version)' { python -u $build --octodb $data --work $Work --pfquest $pfquest | Out-Null }

    $msg = @("${version}: server update $(Get-Date -Format 'yyyy-MM-dd')", '',
             "Quests added: $($added.Count), removed: $($gone.Count).")
    if ($added) { $msg += ($addedNames | ForEach-Object { "  + $_" }) }
    if ($gone) { $msg += ($gone | Select-Object -First 40 | ForEach-Object { "  - $_" }) }
    $msgFile = Join-Path $cache 'commit-msg.txt'
    [System.IO.File]::WriteAllText($msgFile, ($msg -join "`n") + "`n")
    RepoGit add -- @generated tools/build.py
    Run 'git commit' { git -C $repo commit -q -F $msgFile }
    Write-Host "Committed $version ($(RepoGit rev-parse --short HEAD))"

    if (-not $NoPush) {
        Run 'git push' { git -C $repo push -q origin HEAD:main }
        Write-Host 'Pushed to GitHub.'
    }

    #[[ The installed copy is a git clone. Bringing it to the same commit keeps
    #   OctoLauncher's "Update all" from treating it as locally edited and
    #   resetting it. ]]
    if (Test-Path (Join-Path $installed '.git')) {
        $from = if ($NoPush) { $repo } else { 'origin' }
        & git -C $installed pull -q --ff-only $from main
        if ($LASTEXITCODE -eq 0) {
            Write-Host "Installed copy updated to $(& git -C $installed rev-parse --short HEAD). /reload or relog to load it."
        } else {
            Write-Host 'Could not fast-forward the installed copy; update it from OctoLauncher.' -ForegroundColor Yellow
        }
    }
} finally {
    Pop-Location
    $lockFile.Close()
    Remove-Item $lock -ErrorAction SilentlyContinue
    Write-Host "`nLog: $log"
    try { Stop-Transcript | Out-Null } catch { }
}
